#!/usr/bin/env python3
"""Rule-v1 vs model evaluation on synthetic data (daily-small scale,
the deployed profile). All data is synthetic — see RESULTS.md.

Methods:
  rule-v1 : the M2 placeholder rule exactly as deployed
            (known dest -> LOW; amount >= 0.008 ETH -> HIGH;
             first-seen dest -> MEDIUM; else LOW)
  model   : the shipped Isolation Forest (model/model.json)

Scenarios: held-out normal traffic, 3 attack types (full drain,
small-amount barrage, concentration to a new destination) and
2 rare-but-legit types (3x median to a known address; first
withdrawal after a 30-day pause).
"""
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from model.features import PROFILES, compute_features
from model.gen_data import gen_history
from model.scorer import Model

KNOWN_ADDRS = set()
HIGH_AMOUNT = 0.008  # ETH, as deployed in M2


def rule_v1(profile, history, to, amount, timestamp, balance):
    known = {h[1] for h in history} | set(profile.get("known_destinations", [])) | KNOWN_ADDRS
    if to in known:
        return "LOW"
    if amount >= HIGH_AMOUNT:
        return "HIGH"
    if to not in {h[1] for h in history}:
        return "MEDIUM"
    return "LOW"


def run():
    model = Model.load()
    profile, hist, bals = gen_history("daily-small", days=180, seed=42)
    runtime_profile = dict(PROFILES["daily-small"])
    runtime_profile["known_destinations"] = list(profile["known_destinations"])

    def both(history, to, amount, t, balance):
        feats = compute_features(runtime_profile, history, to, amount, t, balance)
        return rule_v1(runtime_profile, history, to, amount, t, balance), model.severity(feats)[0]

    lines = []
    lines.append("# Evaluation — rule-v1 vs model (synthetic data)\n")
    lines.append("All traffic is synthetic, generated by model/gen_data.py at the")
    lines.append("daily-small scale (the deployed profile). Numbers are reported")
    lines.append("as computed, including where the model loses.\n")

    # --- held-out normal traffic ---
    _, h2, b2 = gen_history("daily-small", days=180, seed=777)
    rc, mc = Counter(), Counter()
    for i, h in enumerate(h2):
        r, m = both(h2[:i], h[1], h[2], h[0], b2[i])
        rc[r] += 1
        mc[m] += 1
    n = len(h2)
    lines.append(f"## Held-out normal traffic (n={n})\n")
    lines.append("| method | LOW | MEDIUM | HIGH | flagged (>=MEDIUM) |")
    lines.append("|---|---|---|---|---|")
    for name, c in (("rule-v1", rc), ("model", mc)):
        flagged = (c["MEDIUM"] + c["HIGH"]) / n * 100
        lines.append(f"| {name} | {c['LOW']} | {c['MEDIUM']} | {c['HIGH']} | {flagged:.1f}% |")
    lines.append("")

    # --- attacks ---
    base_hist = hist
    bal = 0.5
    t0 = hist[-1][0] + 7200

    def attack_report(name, sequence):
        """sequence: list of (to, amount, dt_seconds). Detection = first
        index flagged >=MEDIUM (and first HIGH)."""
        h = list(base_hist)
        t = t0
        r_first = m_first = r_high = m_high = None
        for i, (to, amount, dt) in enumerate(sequence):
            t += dt
            r, m = both(h, to, amount, t, bal)
            if r_first is None and r in ("MEDIUM", "HIGH"):
                r_first = i + 1
            if m_first is None and m in ("MEDIUM", "HIGH"):
                m_first = i + 1
            if r_high is None and r == "HIGH":
                r_high = i + 1
            if m_high is None and m == "HIGH":
                m_high = i + 1
            h.append((t, to, amount))
        lines.append(
            f"| {name} | {r_first or '-'} | {m_first or '-'} | {r_high or '-'} | {m_high or '-'} |"
        )

    lines.append("## Attacks (withdrawal # at first flag)\n")
    lines.append("| scenario | rule >=MED | model >=MED | rule HIGH | model HIGH |")
    lines.append("|---|---|---|---|---|")
    attack_report("full drain: 0.475 ETH to fresh addr", [("0xAttacker", 0.475, 0)])
    attack_report("barrage: 10 x 0.004 ETH to fresh addr, 5 min apart",
                  [("0xAttacker", 0.004, 300)] * 10)
    attack_report("concentration: 5 x 0.015 ETH to one fresh addr, 1 h apart",
                  [("0xAttacker", 0.015, 3600)] * 5)
    lines.append("")

    # --- rare but legit ---
    lines.append("## Rare-but-legit (LOW = passed through)\n")
    lines.append("| scenario | rule-v1 | model |")
    lines.append("|---|---|---|")
    known = profile["known_destinations"][0]
    r, m = both(base_hist, known, 0.03, t0, bal)
    lines.append(f"| 3x median amount to a known address | {r} | {m} |")
    r, m = both(base_hist, known, 0.011, t0 + 30 * 86400, bal)
    lines.append(f"| normal amount after a 30-day pause | {r} | {m} |")
    lines.append("")
    lines.append("Notes: a MEDIUM verdict vetoes only that one withdrawal and the")
    lines.append("owner can unfreeze/override; two MEDIUMs within an hour escalate")
    lines.append("to a full freeze by design. A HIGH on a rare-legit withdrawal is")
    lines.append("therefore costly but recoverable — and it is reported here as-is.")

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "RESULTS.md")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    run()
